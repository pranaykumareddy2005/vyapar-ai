"""Run the conversational AI evaluation against a live provider.

Usage (from the repo root, with the venv active):

    python -m evals.run_eval                 # uses AI_PROVIDER from the environment
    AI_PROVIDER=ollama python -m evals.run_eval
    python -m evals.run_eval --provider mock # deterministic offline baseline

Honesty contract: if the selected provider is unreachable (e.g. Ollama not
running or the model not pulled), this prints the failure and exits non-zero. It
never fabricates results. Latency is wall-clock per ``resolve`` call.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from app.config import get_settings
from app.conversation.provider import ConversationAiProvider, MockConversationAiProvider

from evals.dataset import CASES
from evals.harness import EvalResults, run


def _build_provider(name: str) -> ConversationAiProvider:
    if name == "mock":
        return MockConversationAiProvider()
    if name == "ollama":
        from app.conversation.adapters.ollama import OllamaConversationAdapter

        s = get_settings()
        return OllamaConversationAdapter(
            base_url=s.ollama_base_url,
            model=s.ollama_conversation_model,
            timeout=s.ollama_request_timeout_seconds,
        )
    if name == "gemini":
        from app.conversation.adapters.gemini import GeminiConversationAdapter

        s = get_settings()
        return GeminiConversationAdapter(
            api_key=s.ai_api_key, model=s.ai_model, timeout=s.ai_request_timeout_seconds
        )
    raise SystemExit(f"unknown provider: {name}")


def _line(label: str, m: object) -> str:
    from evals.harness import Metric

    assert isinstance(m, Metric)
    return f"| {label} | {m.correct}/{m.total} | {m.pct:.1f}% |"


def format_report(provider_name: str, model: str, results: EvalResults) -> str:
    rows = [
        _line("Intent accuracy", results.intent),
        _line("Product resolution", results.product),
        _line("Quantity extraction", results.quantity),
        _line("Direction extraction", results.direction),
        _line("Model language detection", results.model_language),
        _line("Response language (script-based)", results.response_language),
        _line("Unsupported detection", results.unsupported),
        _line("Injection rejection", results.injection_rejection),
    ]
    lang_rows = [
        _line(f"Intent accuracy - {bucket}", metric)
        for bucket, metric in results.by_language.items()
        if metric.total
    ]
    lines = [
        f"Provider: **{provider_name}**  Model: **{model}**",
        f"Cases: {len(CASES)}  Provider errors: {results.errors}  "
        f"Avg latency: {results.avg_latency_ms:.0f} ms",
        "",
        "| Metric | Correct | Accuracy |",
        "|--------|---------|----------|",
        *rows,
        "",
        "Multilingual intent accuracy (per language):",
        "",
        "| Language | Correct | Accuracy |",
        "|----------|---------|----------|",
        *lang_rows,
    ]
    if results.failures:
        lines += ["", "Misclassifications / errors:", ""]
        lines += [f"- {f}" for f in results.failures]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Conversational AI evaluation")
    parser.add_argument("--provider", default=get_settings().ai_provider)
    parser.add_argument("--out", default="docs/ai/evaluation_report.md")
    args = parser.parse_args()

    try:
        provider = _build_provider(args.provider)
    except Exception as exc:  # top-level CLI guard: report and exit, never crash
        print(f"Could not construct provider {args.provider!r}: {exc}", file=sys.stderr)
        return 2

    model = getattr(provider, "model", "?")
    print(f"Running {len(CASES)} cases against {args.provider} ({model}) ...", file=sys.stderr)
    results = run(provider)

    if results.errors == len(CASES):
        print(
            "All calls failed - is the provider reachable? (No report written.)",
            file=sys.stderr,
        )
        return 1

    report = format_report(args.provider, str(model), results)
    # Write the full report (which may contain Telugu/Hindi) as UTF-8; the Windows
    # console is cp1252, so only an ASCII-safe summary goes to stdout.
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Conversational AI Evaluation Report\n\n_Generated by `python -m evals.run_eval`._\n\n"
    )
    out_path.write_text(header + report + "\n", encoding="utf-8")

    print(f"Report written to {out_path}", file=sys.stderr)
    print(
        f"provider={args.provider} model={model} "
        f"intent={results.intent.pct:.1f}% "
        f"quantity={results.quantity.pct:.1f}% "
        f"direction={results.direction.pct:.1f}% "
        f"product={results.product.pct:.1f}% "
        f"unsupported={results.unsupported.pct:.1f}% "
        f"injection_reject={results.injection_rejection.pct:.1f}% "
        f"resp_lang={results.response_language.pct:.1f}% "
        f"avg_latency={results.avg_latency_ms:.0f}ms "
        f"errors={results.errors}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
